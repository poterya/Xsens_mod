# C++ formatting helpers


def fmt_float(v: float) -> str:
    if not math.isfinite(v):
        raise ValueError(f"non-finite value in weights: {v}")
    return f"{v:.9e}f"


def emit_float_array(name: str, arr: np.ndarray, per_line: int = 6) -> str:
    flat = arr.reshape(-1)
    lines: list[str] = [f"const float {name}[{flat.size}] = {{"]
    for i in range(0, flat.size, per_line):
        chunk = ", ".join(fmt_float(float(v)) for v in flat[i:i + per_line])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


