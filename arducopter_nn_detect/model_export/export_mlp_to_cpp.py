#!/usr/bin/env python3
"""Export the v2.0 MLP fault detector (from branch `nir`) to flat C++ tables.

Input:  propeller_fault_mlp_keras_set05.pt (state_dict for MLPDetector,
        architecture: BatchNorm1d(80) -> Linear(80,128)+ReLU -> Linear(128,64)+ReLU
        -> Linear(64,32)+ReLU -> Linear(32,1))

Output:
  - ../files/ArduCopter/nn_detect_model.h
  - ../files/ArduCopter/nn_detect_model.cpp

The exported C++ exposes:
  - NNDetectModel::predict_proba(features[80]) -> sigmoid(net(features))
  - feature count / window size / feature names (in the exact order the
    Python `extract_features` returns).

After writing the C++ tables we also run the PyTorch model against a
deterministic synthetic window, compute the C++-side features with a
Python reference implementation that mirrors the C++ verbatim, and check
that the resulting probability stays well inside the model's decision
margin so the snapshot stays self-consistent.
"""
from __future__ import annotations

import argparse
import math
from pathlib import Path
from typing import Iterable

import numpy as np
import torch
import torch.nn as nn

from feature_extraction import extract_features  # noqa: E402

THIS_DIR = Path(__file__).resolve().parent
DEFAULT_PT = THIS_DIR / "propeller_fault_mlp_keras_set05.pt"
DEFAULT_OUT = THIS_DIR.parent / "files" / "ArduCopter"

BN_EPS = 1e-5  # PyTorch BatchNorm1d default

# Order of feature names produced by extract_features for an arbitrary window;
# this is what we bake into the C++ feature extractor.
WINDOW_SIZE = 50
SAMPLE_RATE_HZ = 100.0


class MLPDetector(nn.Module):
    """Mirror of the training-time net (see src/apps/start_detection.py)."""

    def __init__(self, in_features: int = 80, dropout: float = 0.3) -> None:
        super().__init__()
        self.net = nn.Sequential(
            nn.BatchNorm1d(in_features),
            nn.Linear(in_features, 128),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
            nn.Linear(128, 64),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
            nn.Linear(64, 32),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
            nn.Linear(32, 1),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.net(x).squeeze(-1)


def feature_name_order() -> list[str]:
    z = np.zeros(WINDOW_SIZE, dtype=float)
    return list(extract_features(z, z, z, z).keys())


