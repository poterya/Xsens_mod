# ---------------------------------------------------------------------------
# Python-side mirror of the C++ feature extractor. Used to verify that the
# C++ output (computed by the model_export verification path) matches the
# Python `extract_features` reference within tight numerical tolerance.


def _stats_block(x: np.ndarray) -> dict:
    n = x.size
    m = float(x.mean())
    d = x - m
    m2 = float(np.mean(d * d))
    m3 = float(np.mean(d * d * d))
    m4 = float(np.mean(d * d * d * d))
    std_pop = math.sqrt(m2)
    sorted_x = np.sort(x)

    def perc(q):
        pos = (q / 100.0) * (n - 1)
        lo = int(pos)
        hi = min(lo + 1, n - 1)
        frac = pos - lo
        return float(sorted_x[lo] + (sorted_x[hi] - sorted_x[lo]) * frac)

    median = perc(50.0)
    iqr = perc(75.0) - perc(25.0)
    p90 = perc(90.0)
    if std_pop > 1e-12:
        g1 = m3 / (m2 ** 1.5)
        g2 = (m4 / (m2 * m2)) - 3.0
        skew = math.sqrt(n * (n - 1)) / (n - 2) * g1
        kurt = ((n - 1) / ((n - 2) * (n - 3))) * ((n + 1) * g2 + 6)
    else:
        skew = 0.0
        kurt = 0.0
    return {
        "mean": m,
        "std": std_pop,
        "max": float(x.max()),
        "min": float(x.min()),
        "range": float(x.max() - x.min()),
        "median": median,
        "iqr": iqr,
        "p90": p90,
        "skew": skew,
        "kurtosis": kurt,
    }


def _spectral_block(x: np.ndarray, fs: float = SAMPLE_RATE_HZ) -> dict:
    n = x.size
    out = {
        "dom_freq": 0.0,
        "e_0_5": 0.0,
        "e_5_10": 0.0,
        "e_10_20": 0.0,
        "e_20_50": 0.0,
        "spec_entropy": 0.0,
    }
    v = x - x.mean()
    if v.std() < 1e-12:
        return out
    spectrum = np.abs(np.fft.rfft(v))
    freqs = np.fft.rfftfreq(n, d=1.0 / fs)
    power = spectrum * spectrum
    tp_safe = float(power.sum()) + 1e-12
    if spectrum.size > 1:
        idx = int(np.argmax(spectrum[1:])) + 1
        out["dom_freq"] = float(freqs[idx])

    def band(lo, hi):
        mask = (freqs >= lo) & (freqs < hi)
        return float(power[mask].sum() / tp_safe)

    out["e_0_5"]   = band(0.0, 5.0)
    out["e_5_10"]  = band(5.0, 10.0)
    out["e_10_20"] = band(10.0, 20.0)
    out["e_20_50"] = band(20.0, 50.0)
    p = power / tp_safe
    p = p[p > 1e-12]
    if p.size:
        out["spec_entropy"] = float(-np.sum(p * np.log(p)))
    return out


def _cpp_mirror_features(total, rms_x, rms_y, rms_z) -> np.ndarray:
    st_t = _stats_block(np.asarray(total, dtype=float))
    st_x = _stats_block(np.asarray(rms_x, dtype=float))
    st_y = _stats_block(np.asarray(rms_y, dtype=float))
    st_z = _stats_block(np.asarray(rms_z, dtype=float))
    sp_t = _spectral_block(np.asarray(total, dtype=float))
    sp_x = _spectral_block(np.asarray(rms_x, dtype=float))
    sp_y = _spectral_block(np.asarray(rms_y, dtype=float))
    sp_z = _spectral_block(np.asarray(rms_z, dtype=float))

    t_safe = max(st_t["mean"], 1e-9)
    x_safe = max(st_x["mean"], 1e-9)
    y_safe = max(st_y["mean"], 1e-9)
    z_safe = max(st_z["mean"], 1e-9)

    def stats_tuple(s):
        return (s["mean"], s["std"], s["max"], s["min"], s["range"],
                s["median"], s["iqr"], s["p90"], s["skew"], s["kurtosis"])

    diffs = np.abs(np.diff(np.asarray(total, dtype=float)))
    d_mean = float(diffs.mean())
    d_max = float(diffs.max())
    d_std = float(diffs.std())

    # Pearson with population stds (matches Python _safe_corr).
    def corr(a, b):
        a = np.asarray(a, dtype=float)
        b = np.asarray(b, dtype=float)
        sa, sb = float(a.std()), float(b.std())
        if sa < 1e-9 or sb < 1e-9:
            return 0.0
        return float(((a - a.mean()) * (b - b.mean())).mean() / (sa * sb))

    out: list[float] = []
    out.extend(stats_tuple(st_t))
    out.extend(stats_tuple(st_x))
    out.extend(stats_tuple(st_y))
    out.extend(stats_tuple(st_z))
    out.append(st_x["mean"] / t_safe)
    out.append(st_y["mean"] / t_safe)
    out.append(st_z["mean"] / t_safe)
    out.append(st_x["mean"] / y_safe)
    out.append(st_x["mean"] / z_safe)
    out.append(st_y["mean"] / z_safe)
    axis_max = max(st_x["mean"], st_y["mean"], st_z["mean"])
    out.append(axis_max / t_safe)
    out.append(d_mean)
    out.append(d_max)
    out.append(d_std)
    for sp in (sp_t, sp_x, sp_y, sp_z):
        out.append(sp["dom_freq"])
        out.append(sp["e_0_5"])
        out.append(sp["e_5_10"])
        out.append(sp["e_10_20"])
        out.append(sp["e_20_50"])
        out.append(sp["spec_entropy"])
    out.append(corr(rms_x, rms_y))
    out.append(corr(rms_x, rms_z))
    out.append(corr(rms_y, rms_z))
    out.append((st_x["mean"] - st_y["mean"]) / t_safe)
    out.append((st_x["mean"] - st_z["mean"]) / t_safe)
    out.append((st_y["mean"] - st_z["mean"]) / t_safe)

    return np.array(out, dtype=np.float64)


def verify_features(feature_names: list[str]) -> None:
    rng = np.random.default_rng(42)
    max_abs = 0.0
    for trial in range(10):
        window = rng.uniform(0.0, 1.5, size=(WINDOW_SIZE, 3)).astype(np.float64)
        rms_x = window[:, 0]
        rms_y = window[:, 1]
        rms_z = window[:, 2]
        total = np.sqrt(rms_x ** 2 + rms_y ** 2 + rms_z ** 2)
        py_feats = extract_features(total, rms_x, rms_y, rms_z)
        ref = np.array([py_feats[n] for n in feature_names], dtype=np.float64)
        cpp_like = _cpp_mirror_features(total, rms_x, rms_y, rms_z)
        diff = np.abs(ref - cpp_like)
        idx = int(np.argmax(diff))
        max_abs = max(max_abs, float(diff.max()))
        print(f"  trial {trial}: max|py - cpp_mirror| = {float(diff.max()):.3e}"
              f"  worst feature = {feature_names[idx]}"
              f"  (py={ref[idx]:.6f} cpp={cpp_like[idx]:.6f})")
    assert max_abs < 1e-8, max_abs
    print(f"feature mirror OK (max abs diff = {max_abs:.2e})")


