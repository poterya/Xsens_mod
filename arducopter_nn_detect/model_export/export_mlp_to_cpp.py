MODEL_H_TEMPLATE = """// AUTO-GENERATED by arducopter_nn_detect/model_export/export_mlp_to_cpp.py
// DO NOT EDIT BY HAND.
//
// MLP propeller-fault detector exported from
// models/mlp/propeller_fault_mlp_keras_set05.pt (branch `nir`).
// Architecture (eval mode):
//   BatchNorm1d({IN}) -> Linear({IN},{H1})+ReLU
//   -> Linear({H1},{H2})+ReLU
//   -> Linear({H2},{H3})+ReLU
//   -> Linear({H3},1) (logit)
//   -> sigmoid -> P(class == 1 = DEFORMED)
//
// predict_proba(features) returns P(class==1) in [0,1].

#pragma once

#include <stdint.h>

namespace NNDetectModel {{

constexpr uint16_t FEATURE_COUNT = {FEATURE_COUNT};
constexpr uint16_t WINDOW_SIZE   = {WINDOW_SIZE};

extern const char * const FEATURE_NAMES[FEATURE_COUNT];

// Returns P(class == 1) in [0,1].
float predict_proba(const float features[FEATURE_COUNT]);

}}  // namespace NNDetectModel
"""

MODEL_CPP_TEMPLATE = """// AUTO-GENERATED by arducopter_nn_detect/model_export/export_mlp_to_cpp.py
// DO NOT EDIT BY HAND.
//
// MLP propeller-fault detector. See nn_detect_model.h for the architecture.

#include "nn_detect_model.h"

#include <math.h>

namespace NNDetectModel {{

namespace {{

constexpr uint16_t IN_DIM = {IN};
constexpr uint16_t H1     = {H1};
constexpr uint16_t H2     = {H2};
constexpr uint16_t H3     = {H3};

// BatchNorm1d in eval mode: y = (x - running_mean) / sqrt(running_var + eps) *
//                                weight + bias. Precomputed scale/shift so
// the inner loop is a single mul+add.
{BN_SCALE}

{BN_SHIFT}

// Linear weights are stored row-major: W[row * in_dim + col].
{L1_W}

{L1_B}

{L2_W}

{L2_B}

{L3_W}

{L3_B}

{L4_W}

{L4_B}

inline float relu(float x) {{ return x > 0.0f ? x : 0.0f; }}

void forward(const float in_features[IN_DIM], float &out_logit)
{{
    float x0[IN_DIM];
    for (uint16_t i = 0; i < IN_DIM; i++) {{
        x0[i] = in_features[i] * BN_SCALE[i] + BN_SHIFT[i];
    }}

    float x1[H1];
    for (uint16_t j = 0; j < H1; j++) {{
        float s = L1_BIAS[j];
        const float *row = &L1_WEIGHT[j * IN_DIM];
        for (uint16_t i = 0; i < IN_DIM; i++) {{
            s += row[i] * x0[i];
        }}
        x1[j] = relu(s);
    }}

    float x2[H2];
    for (uint16_t j = 0; j < H2; j++) {{
        float s = L2_BIAS[j];
        const float *row = &L2_WEIGHT[j * H1];
        for (uint16_t i = 0; i < H1; i++) {{
            s += row[i] * x1[i];
        }}
        x2[j] = relu(s);
    }}

    float x3[H3];
    for (uint16_t j = 0; j < H3; j++) {{
        float s = L3_BIAS[j];
        const float *row = &L3_WEIGHT[j * H2];
        for (uint16_t i = 0; i < H2; i++) {{
            s += row[i] * x2[i];
        }}
        x3[j] = relu(s);
    }}

    float logit = L4_BIAS[0];
    for (uint16_t i = 0; i < H3; i++) {{
        logit += L4_WEIGHT[i] * x3[i];
    }}
    out_logit = logit;
}}

}}  // namespace

float predict_proba(const float features[FEATURE_COUNT])
{{
    float logit = 0.0f;
    forward(features, logit);
    // sigmoid, numerically stable for both signs of logit.
    if (logit >= 0.0f) {{
        const float z = expf(-logit);
        return 1.0f / (1.0f + z);
    }}
    const float z = expf(logit);
    return z / (1.0f + z);
}}

{FEATURE_NAMES}

}}  // namespace NNDetectModel
"""


def emit_feature_names(names: list[str]) -> str:
    lines = ["const char * const FEATURE_NAMES[FEATURE_COUNT] = {"]
    for n in names:
        lines.append(f'    "{n}",')
    lines.append("};")
    return "\n".join(lines)


def export_model(pt_path: Path, out_dir: Path) -> None:
    model = MLPDetector(in_features=80)
    state = torch.load(pt_path, map_location="cpu", weights_only=True)
    model.load_state_dict(state)
    model.eval()

    bn = model.net[0]
    l1 = model.net[1]
    l2 = model.net[4]
    l3 = model.net[7]
    l4 = model.net[10]

    bn_w = bn.weight.detach().cpu().numpy()
    bn_b = bn.bias.detach().cpu().numpy()
    bn_m = bn.running_mean.detach().cpu().numpy()
    bn_v = bn.running_var.detach().cpu().numpy()

    bn_scale = bn_w / np.sqrt(bn_v + BN_EPS)
    bn_shift = bn_b - bn_scale * bn_m

    feature_names = feature_name_order()
    assert len(feature_names) == 80, len(feature_names)

    cpp = MODEL_CPP_TEMPLATE.format(
        IN=80,
        H1=128,
        H2=64,
        H3=32,
        BN_SCALE=emit_float_array("BN_SCALE", bn_scale.astype(np.float32)),
        BN_SHIFT=emit_float_array("BN_SHIFT", bn_shift.astype(np.float32)),
        L1_W=emit_float_array("L1_WEIGHT", l1.weight.detach().cpu().numpy().astype(np.float32)),
        L1_B=emit_float_array("L1_BIAS",   l1.bias.detach().cpu().numpy().astype(np.float32)),
        L2_W=emit_float_array("L2_WEIGHT", l2.weight.detach().cpu().numpy().astype(np.float32)),
        L2_B=emit_float_array("L2_BIAS",   l2.bias.detach().cpu().numpy().astype(np.float32)),
        L3_W=emit_float_array("L3_WEIGHT", l3.weight.detach().cpu().numpy().astype(np.float32)),
        L3_B=emit_float_array("L3_BIAS",   l3.bias.detach().cpu().numpy().astype(np.float32)),
        L4_W=emit_float_array("L4_WEIGHT", l4.weight.detach().cpu().numpy().astype(np.float32)),
        L4_B=emit_float_array("L4_BIAS",   l4.bias.detach().cpu().numpy().astype(np.float32)),
        FEATURE_NAMES=emit_feature_names(feature_names),
    )

    header = MODEL_H_TEMPLATE.format(
        IN=80, H1=128, H2=64, H3=32,
        FEATURE_COUNT=80, WINDOW_SIZE=WINDOW_SIZE,
    )

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "nn_detect_model.h").write_text(header)
    (out_dir / "nn_detect_model.cpp").write_text(cpp)
    print(f"Wrote {out_dir/'nn_detect_model.h'}")
    print(f"Wrote {out_dir/'nn_detect_model.cpp'}")

    # Sanity check: run PyTorch on a couple of windows. Even with a synthetic
    # window the model should never go NaN and should stay inside [0, 1].
    rng = np.random.default_rng(0)
    for trial in range(3):
        window = rng.normal(0.5, 0.05, size=(WINDOW_SIZE, 4)).astype(np.float32)
        total = np.linalg.norm(window[:, 1:], axis=1)
        rms_x = window[:, 1]
        rms_y = window[:, 2]
        rms_z = window[:, 3]
        feats = extract_features(total, rms_x, rms_y, rms_z)
        vec = np.array([feats[n] for n in feature_names], dtype=np.float32)
        with torch.no_grad():
            p = float(torch.sigmoid(model(torch.from_numpy(vec).unsqueeze(0))).item())
        assert 0.0 <= p <= 1.0, p
        print(f"  trial {trial}: P(fault) = {p:.6f}")

    return feature_names


